import fs from 'fs'
import path from 'path'

import fg from 'fast-glob'
import type { Plugin } from 'vite'

const LOCALE_GLOBS = [
  'src/features/**/*.locales.en.json',
  'src/common/**/*.locales.en.json',
  'src/routes/**/*.locales.en.json',
  'src/setup/**/*.locales.en.json',
]
const OUTPUT_FILE = 'src/setup/i18n/i18n.types.d.ts'

export function deriveNamespace(filePath: string): string {
  const normalized = filePath.replace(/\\/g, '/')
  const afterSrc = normalized.replace(/^(.*\/)?src\//, '')
  const parts = afterSrc.split('/')
  parts.pop()
  return parts.map(p => p.replace(/^_/, '')).join('.')
}

function generateTypes(root: string): void {
  const localeFiles = fg.sync(LOCALE_GLOBS, { cwd: root }).sort()

  const imports: Array<string> = []
  const resourceEntries: Array<string> = []

  for (const file of localeFiles) {
    const ns = deriveNamespace(file)
    const varName = ns.replace(/[^a-zA-Z0-9]/g, '_')
    const importPath = `@/${file.replace(/^src\//, '')}`
    imports.push(`import type ${varName} from '${importPath}'`)
    resourceEntries.push(`      '${ns}': typeof ${varName}`)
  }

  const namespaces = localeFiles.map(deriveNamespace)
  const topLevel = namespaces.length > 0 ? namespaces.reduce((a, b) => (a.split('.').length <= b.split('.').length ? a : b)) : 'app'

  const resourcesBlock = resourceEntries.length > 0 ? `{\n${resourceEntries.join('\n')}\n    }` : 'Record<string, never>'

  const content = `// This file is auto-generated by the i18n-types-plugin. Do not edit manually.
${imports.join('\n')}${imports.length > 0 ? '\n' : ''}
declare global {
  interface Window {
    setLang: (lng: string) => void
  }
}

declare module 'i18next' {
  interface CustomTypeOptions {
    defaultNS: '${topLevel}'
    resources: ${resourcesBlock}
  }
}
`

  const outputPath = path.resolve(root, OUTPUT_FILE)
  fs.writeFileSync(outputPath, content, 'utf-8')
}

export function i18nTypesPlugin(): Plugin {
  let root: string

  return {
    name: 'i18n-types',
    configResolved(config) {
      root = config.root
    },
    buildStart() {
      generateTypes(root)
    },
    configureServer(server) {
      const isLocaleFile = (file: string) =>
        (file.includes('features') || file.includes('common') || file.includes('routes') || file.includes('setup')) &&
        file.endsWith('.locales.en.json')

      server.watcher.on('add', file => {
        if (isLocaleFile(file)) generateTypes(root)
      })
      server.watcher.on('unlink', file => {
        if (isLocaleFile(file)) generateTypes(root)
      })
    },
    handleHotUpdate({ file, server }) {
      if ((file.includes('features') || file.includes('common')) && file.endsWith('.tsx')) {
        server.ws.send({ type: 'custom', event: 'i18n:tsx-updated' })
      }
    },
  }
}
